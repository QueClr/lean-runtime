//! Constant operands must give the results of run-time operands (Lean's C always
//! passes run-time values to libm): LLVM evaluates a libm call with constant
//! operands at compile time, and its evaluation need not be glibc's (`exp2` is
//! folded as `pow(2, x)`, `f32` functions are evaluated in `double` and
//! rounded). Rows cannot catch this, since their operands are read at run time.
//! So every libm function here is called on literal operands, which the
//! compiler may fold, and on the same operands through `black_box`, and the
//! two must agree bit for bit (NaN canonical, as `Float.toBits`).
//!
//! Folding happens only in optimized builds: `scripts/check.sh` runs this test
//! with `--release`; a debug build ignores it. The operands are 40 per function
//! drawn over its domain with a fixed seed, plus a few chosen ones
//! (`35.74477454358792` is leanrs's `exp2` counterexample, review S1-1).

// The operands are written with every digit Lean prints, on purpose.
#![allow(clippy::excessive_precision)]

use core::hint::black_box;

use lean_runtime::semantics::{float, float32, libm};

macro_rules! unary {
    ($name:ident, $f:path, $bits:path, [$($c:expr),* $(,)?]) => {
        #[test]
        #[cfg_attr(debug_assertions, ignore = "constant folding happens in optimized builds")]
        fn $name() {
            let folded = [$( $bits($f($c)) ),*];
            let opaque = [$( $bits($f(black_box($c))) ),*];
            let operands = [$( $c ),*];
            for i in 0..operands.len() {
                assert_eq!(folded[i], opaque[i], "{}({:?}): folded {:#x}, run time {:#x}",
                    stringify!($f), operands[i], folded[i], opaque[i]);
            }
        }
    };
}

macro_rules! binary {
    ($name:ident, $f:path, $bits:path, [$(($a:expr, $b:expr)),* $(,)?]) => {
        #[test]
        #[cfg_attr(debug_assertions, ignore = "constant folding happens in optimized builds")]
        fn $name() {
            let folded = [$( $bits($f($a, $b)) ),*];
            let opaque = [$( $bits($f(black_box($a), black_box($b))) ),*];
            let operands = [$( ($a, $b) ),*];
            for i in 0..operands.len() {
                assert_eq!(folded[i], opaque[i], "{}({:?}): folded {:#x}, run time {:#x}",
                    stringify!($f), operands[i], folded[i], opaque[i]);
            }
        }
    };
}
